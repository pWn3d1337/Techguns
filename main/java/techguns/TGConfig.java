	public static boolean allowUnsafemode(EntityPlayer player){
		boolean op = FMLCommonHandler.instance().getMinecraftServerInstance().getConfigurationManager().func_152596_g(player.getGameProfile());
		return op || !TGConfig.forceSafemodeNonOp;
	}
	
